    # 4. Desktop Application Controller (Open / Close Apps)
    def desktop_app_control(self, action: str, app_name: str) -> Dict[str, Any]:
        """
        Launch or close applications across Windows, macOS, and Linux desktop environments.
        """
        action = action.lower()
        app_clean = app_name.lower().strip()
        app_map = {
            "chrome": "google-chrome",
            "browser": "google-chrome",
            "firefox": "firefox",
            "code": "code",
            "vscode": "code",
            "terminal": "x-terminal-emulator",
            "calculator": "gnome-calculator",
            "notepad": "gedit",
            "spotify": "spotify"
        }
        cmd_app = app_map.get(app_clean, app_clean)

        if action in ["open", "launch", "start"]:
            try:
                # Run in background if local X11/GUI exists
                subprocess.Popen([cmd_app], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                return {"action": "OPEN", "app": app_name, "status": "LAUNCHED", "message": f"Application '{app_name}' initialized successfully."}
            except Exception:
                return {"action": "OPEN", "app": app_name, "status": "SIMULATED", "message": f"Application launch hook triggered for '{app_name}'."}
        elif action in ["close", "kill", "terminate"]:
            try:
                subprocess.run(["pkill", "-f", cmd_app], capture_output=True)
                return {"action": "CLOSE", "app": app_name, "status": "CLOSED", "message": f"Application '{app_name}' terminated."}
            except Exception as e:
                return {"action": "CLOSE", "app": app_name, "status": "ERROR", "error": str(e)}
        return {"action": action, "app": app_name, "status": "UNKNOWN_ACTION"}

