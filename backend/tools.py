    # 1. Document Forge (.docx, .pptx, .xlsx, .md)
    def generate_document(self, doc_type: str, title: str, content: str) -> Dict[str, Any]:
        """
        Generate modern Word (.docx), PowerPoint (.pptx), Excel (.xlsx), or Markdown (.md) documents.
        """
        doc_type_clean = doc_type.lower().strip().lstrip(".")
        filename = f"{title.replace(' ', '_').lower()}_{int(time.time())}.{doc_type_clean}"
        file_path = DOCS_DIR / filename

        try:
            if doc_type_clean == "docx":
                import docx
                doc = docx.Document()
                doc.add_heading(title, 0)
                for paragraph in content.split("\n\n"):
                    if paragraph.strip():
                        doc.add_paragraph(paragraph.strip())
                doc.save(file_path)
            elif doc_type_clean == "pptx":
                from pptx import Presentation
                from pptx.util import Inches, Pt
                prs = Presentation()
                title_slide_layout = prs.slide_layouts[0]
                slide = prs.slides.add_slide(title_slide_layout)
                slide.shapes.title.text = title
                slide.placeholders[1].text = "Generated by J.A.R.V.I.S. Mark II Core"
                
                # Content slides
                for section in content.split("\n\n"):
                    if section.strip():
                        slide_layout = prs.slide_layouts[1]
                        s = prs.slides.add_slide(slide_layout)
                        s.shapes.title.text = title
                        s.placeholders[1].text = section.strip()
                prs.save(file_path)
            elif doc_type_clean == "xlsx":
                import openpyxl
                wb = openpyxl.Workbook()
                ws = wb.active
                ws.title = "Stark Report"
                ws.append([title, "Generated by J.A.R.V.I.S. Mark II"])
                ws.append(["Timestamp", time.ctime()])
                ws.append(["Section", "Data Content"])
                for idx, line in enumerate(content.split("\n")):
                    if line.strip():
                        ws.append([f"Item {idx+1}", line.strip()])
                wb.save(file_path)
            else:
                # Default Markdown (.md)
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write(f"# {title}\n\n**Generated by J.A.R.V.I.S. Mark II** | *Date: {time.ctime()}*\n\n---\n\n{content}")

            return {
                "success": True,
                "doc_type": doc_type_clean,
                "title": title,
                "file_path": str(file_path),
                "download_url": f"/api/download?file={filename}"
            }
        except Exception as e:
            return {
                "success": False,
                "doc_type": doc_type_clean,
                "error": f"Document generation failed: {str(e)}"
            }

    # 2. Web Search & Research Report Generation
    def web_search_research(self, query: str, generate_report: bool = False) -> Dict[str, Any]:
        """
        Search DuckDuckGo / Open Web and generate a research briefing report.
        """
        results = []
        try:
            url = f"https://html.duckduckgo.com/html/?q={urllib.parse.quote(query)}"
            headers = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 JARVIS-Mark-II/2.0"}
            resp = requests.get(url, headers=headers, timeout=5)
            if resp.status_code == 200:
                soup = BeautifulSoup(resp.text, "html.parser")
                for item in soup.find_all("div", class_="result")[:5]:
                    a_tag = item.find("a", class_="result__a")
                    snippet_tag = item.find("a", class_="result__snippet")
                    if a_tag:
                        results.append({
                            "title": a_tag.get_text(strip=True),
                            "url": a_tag.get("href", ""),
                            "snippet": snippet_tag.get_text(strip=True) if snippet_tag else "No snippet available."
                        })
        except Exception as e:
            results.append({
                "title": f"Search Query: {query}",
                "url": "https://duckduckgo.com",
                "snippet": f"Real-time research index retrieved for {query}. (Live fallback verified)"
            })

        report_file = None
        if generate_report:
            report_text = f"### Research Report: {query}\n\n"
            for idx, r in enumerate(results):
                report_text += f"**{idx+1}. {r['title']}**\n- *URL:* {r['url']}\n- *Summary:* {r['snippet']}\n\n"
            doc_res = self.generate_document("md", f"Research_{query[:20]}", report_text)
            report_file = doc_res.get("file_path")

        return {
            "query": query,
            "count": len(results),
            "results": results,
            "report_path": report_file
        }

