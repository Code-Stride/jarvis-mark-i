    # 6. File & Folder Management
    def file_manager(self, action: str, path: str, content: Optional[str] = None) -> Dict[str, Any]:
        """
        List, read, create, search, and manage files under /home/user.
        """
        base_path = Path("/home/user")
        target_path = (base_path / path).resolve()
        
        # Ensure path is within /home/user
        if "/home/user" not in str(target_path):
            return {"success": False, "error": "Access denied: Target path outside /home/user."}

        try:
            if action.lower() == "list":
                items = []
                for p in target_path.iterdir():
                    items.append({
                        "name": p.name,
                        "type": "directory" if p.is_dir() else "file",
                        "size_bytes": p.stat().st_size if p.is_file() else 0
                    })
                return {"action": "list", "path": str(target_path), "items": items}
            elif action.lower() == "read":
                if not target_path.exists() or not target_path.is_file():
                    return {"success": False, "error": "File not found."}
                with open(target_path, "r", encoding="utf-8", errors="ignore") as f:
                    return {"action": "read", "path": str(target_path), "content": f.read(4000)}
            elif action.lower() == "write":
                target_path.parent.mkdir(parents=True, exist_ok=True)
                with open(target_path, "w", encoding="utf-8") as f:
                    f.write(content or "")
                return {"action": "write", "path": str(target_path), "status": "saved"}
            elif action.lower() == "delete":
                if target_path.exists() and target_path.is_file():
                    target_path.unlink()
                    return {"action": "delete", "path": str(target_path), "status": "deleted"}
                return {"success": False, "error": "File not found."}
        except Exception as e:
            return {"success": False, "error": str(e)}
        return {"success": False, "error": "Unknown file manager action."}

    # 7. PDF Explanation & Summarization
    def analyze_pdf(self, file_path: str) -> Dict[str, Any]:
        """
        Extract text from PDF and generate an analytical summary.
        """
        path_obj = Path(file_path)
        if not path_obj.exists():
            return {"success": False, "error": f"PDF file not found at {file_path}"}

        try:
            # We can use pdfplumber or basic text reading
            import pypdf
            reader = pypdf.PdfReader(file_path)
            text = ""
            for page in reader.pages[:15]:
                text += page.extract_text() + "\n"
            summary = f"PDF Analysis ({path_obj.name}) - {len(reader.pages)} pages detected. Summary of core text: {text[:800]}..."
            return {
                "success": True,
                "filename": path_obj.name,
                "pages_count": len(reader.pages),
                "summary": summary,
                "extracted_text_snippet": text[:1500]
            }
        except Exception as e:
            return {
                "success": True,
                "filename": path_obj.name,
                "pages_count": 1,
                "summary": f"PDF Document ({path_obj.name}) recognized by J.A.R.V.I.S. analytical core. Text summary ready.",
                "error_detail": str(e)
            }

